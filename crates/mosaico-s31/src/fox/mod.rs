//! The fox-dango character: palette sprites composed per frame.
//!
//! The art lives in `assets/fox-dango/` and is packed by
//! `assets/fox-dango/tools/fox_pack.py` into [`data`]: one 128-colour RGB565
//! palette, 20 base poses and their parts, all as row RLE of palette indices.
//!
//! - [`FoxAnimator`] (`animate.rs`): expression plus time to a [`Scene`].
//! - [`Scene`] (`scene.rs`): pose, layers and warp; no allocation.
//! - [`FoxRenderer`] (`render.rs`): scene to an RGB565 canvas.
//! - [`entrance`]: the drop-in after boot, as a canvas offset and squash.
//! - `math.rs`: sine, exp and friends for a target without libm.
//!
//! `docs/FOX_RENDER_PIPELINE.md` walks through the whole path, from the PNG
//! masters to the panel.

