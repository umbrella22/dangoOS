/// Canvas pixel count.
pub const PIXELS: usize = W * H;
/// Transparent palette index in sprite RLE.
pub const TRANSPARENT: u8 = 255;

/// One RLE image placed on the canvas.
#[derive(Clone, Copy, Debug)]
pub struct Img {
    pub x: i16,
    pub y: i16,
    pub w: u16,
    pub h: u16,
    pub off: u32,
    pub len: u32,
    /// Sprite over the black background (moves after the warp).
    pub over_bg: bool,
}

impl Img {
    #[cfg(test)]
    fn rle(&self) -> &'static [u8] {
        &data::BLOB[self.off as usize..(self.off + self.len) as usize]
    }

    fn centre(&self) -> (f32, f32) {
        (
            self.x as f32 + self.w as f32 / 2.0,
            self.y as f32 + self.h as f32 / 2.0,
        )
    }
}

/// One expression: base pose and its parts.
pub struct Pose {
    pub base: Img,
    pub blink: &'static [Img],
    pub mouth_closed: &'static [Img],
    pub mouth_wide: &'static [Img],
    pub ear: &'static [Img],
    pub gaze_left: &'static [Img],
    pub gaze_right: &'static [Img],
    pub symbols: &'static [Img],
    pub tremble: &'static [Img],
    pub spiral: [&'static [Img]; 3],
}

/// The 20 fox poses, in the order of [`data::POSES`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum FoxPose {
    Idle,
    Sleep,
    Curious,
    Happy,
    Puzzled,
    Confused,
    Surprised,
    Panic,
    Angry,
    Satisfied,
    Listening,
    Thinking,
    Speaking,
    Error,
    Tired,
    Dying,
    Annoyed,
    Charging,
    Peering,
    Dazzled,
}

impl FoxPose {
    /// Stable on-disk pose order for skin format version 1.
    pub const ALL: [Self; 20] = [
        Self::Idle,
        Self::Sleep,
        Self::Curious,
        Self::Happy,
        Self::Puzzled,
        Self::Confused,
        Self::Surprised,
        Self::Panic,
        Self::Angry,
        Self::Satisfied,
        Self::Listening,
        Self::Thinking,
        Self::Speaking,
        Self::Error,
        Self::Tired,
        Self::Dying,
        Self::Annoyed,
        Self::Charging,
        Self::Peering,
        Self::Dazzled,
    ];
    pub fn data(self) -> &'static Pose {
        &data::POSES[self as usize]
    }
}

impl From<Expression> for FoxPose {
    fn from(e: Expression) -> Self {
        match e {
            Expression::Idle => Self::Idle,
            Expression::Sleep => Self::Sleep,
            Expression::Curious => Self::Curious,
            Expression::Happy => Self::Happy,
            Expression::Puzzled => Self::Puzzled,
            Expression::Confused => Self::Confused,
            Expression::Surprised => Self::Surprised,
            Expression::Panic => Self::Panic,
            Expression::Angry => Self::Angry,
            Expression::Satisfied => Self::Satisfied,
            Expression::Listening => Self::Listening,
            Expression::Thinking => Self::Thinking,
            Expression::Speaking => Self::Speaking,
            Expression::Error => Self::Error,
            Expression::Tired => Self::Tired,
            Expression::Dying => Self::Dying,
            Expression::Peering => Self::Peering,
            Expression::Dazzled => Self::Dazzled,
        }
    }
}

#[cfg(test)]
mod tests {
    use alloc::vec;
    use alloc::vec::Vec;

    use super::*;

    #[test]
    fn every_image_decodes_to_its_size() {
        for (n, pose) in data::POSES.iter().enumerate() {
            let mut all: Vec<&Img> = vec![&pose.base];
            for list in [
                pose.blink,
                pose.mouth_closed,
                pose.mouth_wide,
                pose.ear,
                pose.gaze_left,
                pose.gaze_right,
                pose.symbols,
                pose.tremble,
            ]
            .into_iter()
            .chain(pose.spiral)
            {
                all.extend(list.iter());
            }
            for img in all {
                let rle = img.rle();
                assert_eq!(rle.len() % 2, 0);
                let mut px = 0usize;
                let mut x = 0usize;
                for pair in rle.chunks_exact(2) {
                    assert!(pair[0] > 0);
                    assert!(pair[1] == TRANSPARENT || (pair[1] as usize) < data::PALETTE.len());
                    x += pair[0] as usize;
                    assert!(x <= img.w as usize, "pose {n}: run crosses the row end");
                    if x == img.w as usize {
                        x = 0;
                    }
                    px += pair[0] as usize;
                }
                assert_eq!(px, img.w as usize * img.h as usize, "pose {n}");
                assert!(img.x >= 0 && img.y >= 0);
                assert!(
                    img.x as usize + img.w as usize <= W && img.y as usize + img.h as usize <= H
                );
            }
        }
    }

    #[test]
    fn base_poses_are_opaque_and_canvas_sized() {
        for pose in &data::POSES {
            assert_eq!((pose.base.w as usize, pose.base.h as usize), (W, H));
            assert!(!pose.base.rle().chunks_exact(2).any(|p| p[1] == TRANSPARENT));
        }
    }

    #[test]
    fn identity_scene_matches_the_palette() {
        let mut r = FoxRenderer::new();
        let mut out = vec![0u16; PIXELS];
        r.render(&Scene::still(FoxPose::Idle), &mut out);
        assert!(out.iter().any(|&p| p != 0), "the fox is drawn");
        assert!(out.iter().all(|p| *p == 0 || data::PALETTE.contains(p)));
    }

    #[test]
    fn a_blink_changes_only_the_eye_patches() {
        let mut r = FoxRenderer::new();
        let mut open = vec![0u16; PIXELS];
        let mut shut = vec![0u16; PIXELS];
        r.render(&Scene::still(FoxPose::Idle), &mut open);
        let mut s = Scene::still(FoxPose::Idle);
        s.under.extend(FoxPose::Idle.data().blink);
        r.render(&s, &mut shut);
        let blink = FoxPose::Idle.data().blink;
        let mut changed = 0;
        for y in 0..H {
            for x in 0..W {
                if open[y * W + x] != shut[y * W + x] {
                    changed += 1;
                    assert!(blink.iter().any(|b| {
                        (b.x as usize..b.x as usize + b.w as usize).contains(&x)
                            && (b.y as usize..b.y as usize + b.h as usize).contains(&y)
                    }));
                }
            }
        }
        assert!(changed > 200);
    }

    #[test]
    fn unchanged_composition_is_reused() {
        let mut r = FoxRenderer::new();
        let mut out = vec![0u16; PIXELS];
        let mut a = FoxAnimator::new(FoxPose::Idle);
        for _ in 0..10 {
            a.advance(50);
            r.render(&a.scene(FoxInput::REST), &mut out);
        }
        assert!(r.reused > 0);
    }

    #[test]
    fn every_pose_animates_for_ten_seconds() {
        let mut r = FoxRenderer::new();
        let mut out = vec![0u16; PIXELS];
        for pose in 0..20u8 {
            // SAFETY-free conversion through the table index.
            let p = [
                FoxPose::Idle,
                FoxPose::Sleep,
                FoxPose::Curious,
                FoxPose::Happy,
                FoxPose::Puzzled,
                FoxPose::Confused,
                FoxPose::Surprised,
                FoxPose::Panic,
                FoxPose::Angry,
                FoxPose::Satisfied,
                FoxPose::Listening,
                FoxPose::Thinking,
                FoxPose::Speaking,
                FoxPose::Error,
                FoxPose::Tired,
                FoxPose::Dying,
                FoxPose::Annoyed,
                FoxPose::Charging,
                FoxPose::Peering,
                FoxPose::Dazzled,
            ][pose as usize];
            let mut a = FoxAnimator::new(FoxPose::Idle);
            a.set_pose(p);
            for _ in 0..200 {
                a.advance(50);
                let s = a.scene(FoxInput {
                    scale_x: 1.03,
                    scale_y: 0.97,
                    offset_x: 4,
                    offset_y: -10,
                    look_x: 5.0,
                });
                r.render(&s, &mut out);
            }
        }
    }

    #[test]
    fn a_switch_shows_the_old_pose_first() {
        let mut a = FoxAnimator::new(FoxPose::Idle);
        a.set_pose(FoxPose::Happy);
        a.advance(10);
        assert_eq!(a.scene(FoxInput::REST).pose, FoxPose::Idle);
        a.advance(100);
        assert_eq!(a.scene(FoxInput::REST).pose, FoxPose::Happy);
    }
}
