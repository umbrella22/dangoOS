//! Character rendering: external palette sprites composed per frame.
//!
//! Full characters are validated packages under `resources/skins/`, installed on
//! NAND. [`data`] contains only one static missing-character placeholder.
//!
//! - [`FoxAnimator`] (`animate.rs`): expression plus time to a [`Scene`].
//! - [`Scene`] (`scene.rs`): pose, layers and warp; no allocation.
//! - [`FoxRenderer`] (`render.rs`): scene to an RGB565 canvas.
//! - [`entrance`]: the drop-in after boot, as a canvas offset and squash.
//! - `math.rs`: sine, exp and friends for a target without libm.
//!
//! `docs/assets/fox-rendering.md` walks through the whole path, from the PNG
//! masters to the panel.

