#!/usr/bin/env python3
"""Pack the single system placeholder PNG as RGB565 row RLE (requires Pillow).

The PNG is a small generated build input, not a complete character skin.
Repacking needs no image API, source artwork, or credentials.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "crates/os/src/assets"
TABLE = ROOT / "crates/os/src/companion/render/data.rs"
WIDTH, HEIGHT = 352, 336


def pack(path):
    from PIL import Image

    image = Image.open(path).convert("RGB")
    if image.size != (WIDTH, HEIGHT):
        raise ValueError(f"placeholder canvas must be {WIDTH}x{HEIGHT}")
    rgb = image.load()
    pixels = []
    for y in range(HEIGHT):
        for x in range(WIDTH):
            r, g, b = rgb[x, y]
            pixels.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    palette = sorted(set(pixels))
    if not 1 < len(palette) <= 255:
        raise ValueError("placeholder needs 2..255 RGB565 colors")
    indices = {color: index for index, color in enumerate(palette)}
    data = bytearray()
    for y in range(HEIGHT):
        row = pixels[y * WIDTH:(y + 1) * WIDTH]
        x = 0
        while x < WIDTH:
            end = x + 1
            while end < WIDTH and row[end] == row[x] and end - x < 255:
                end += 1
            data.extend((end - x, indices[row[x]]))
            x = end
    table = f'''// @generated by scripts/assets/pack_placeholder.py; do not edit by hand.
// Full characters are external packages under resources/skins/.
use crate::companion::render::{{Img, Pose}};

pub const W: usize = {WIDTH};
pub const H: usize = {HEIGHT};

pub static PALETTE: [u16; {len(palette)}] = [{", ".join(f"0x{color:04x}" for color in palette)}];
pub static BLOB: &[u8] = include_bytes!("../../assets/fox-placeholder.bin");

/// Every expression shares one static image with no animation patches.
pub static PLACEHOLDER_POSE: Pose = Pose {{
    base: Img {{ x: 0, y: 0, w: {WIDTH}, h: {HEIGHT}, off: 0, len: {len(data)}, over_bg: false }},
    blink: &[], mouth_closed: &[], mouth_wide: &[], ear: &[],
    gaze_left: &[], gaze_right: &[], symbols: &[], tremble: &[], spiral: [&[], &[], &[]],
}};
'''.encode()
    return bytes(data), table


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", type=Path, default=ASSETS / "fox-placeholder.png")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    blob, table = pack(args.image)
    for path, data in [(ASSETS / "fox-placeholder.bin", blob), (TABLE, table)]:
        if args.check:
            if path.read_bytes() != data:
                parser.exit(1, f"stale placeholder output: {path}\n")
        else:
            path.write_bytes(data)
    print(f"system placeholder: one image, {len(blob)} RLE bytes")


if __name__ == "__main__":
    main()
