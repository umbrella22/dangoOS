#!/usr/bin/env python3
"""Pack a PhotoCraft PNG as grayscale runs for the allocation-free bootloader.

Each byte starts a run: high nibble is gray4, low nibble encodes length-1.
Nibble 15 extends length 16 by an unsigned LEB128 value. The decoder streams
pixels into a 64-byte hardware FIFO; no full frame or decompressor is needed.
"""
import argparse
import hashlib
from itertools import groupby
import json
from pathlib import Path

from PIL import Image


def encode(values):
    out = bytearray()
    for value, group in groupby(values):
        count = sum(1 for _ in group)
        out.append(value << 4 | min(count - 1, 15))
        if count >= 16:
            count -= 16
            while count >= 128:
                out.append((count & 127) | 128)
                count >>= 7
            out.append(count)
    return bytes(out)


def decode(data):
    out = bytearray()
    at = 0
    while at < len(data):
        value = data[at] >> 4
        count = (data[at] & 15) + 1
        at += 1
        if count == 16:
            shift = 0
            while True:
                byte = data[at]
                at += 1
                count += (byte & 127) << shift
                if not byte & 128:
                    break
                shift += 7
        out.extend(bytes([value]) * count)
    return bytes(out)


def pack(source, output):
    image = Image.open(source).convert("L")
    if image.size != (480, 480):
        raise ValueError("bootloader splash must already be 480 by 480")
    values = bytes((value * 15 + 127) // 255 for value in image.tobytes())
    runs = encode(values)
    if decode(runs) != values:
        raise ValueError("splash run encoding failed its independent pixel comparison")
    text = ["/* Generated by scripts/assets/pack_boot_splash.py; gray4 RLE. */",
            f"/* PNG SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()} */",
            "static const uint8_t dg_splash_runs[] = {"]
    for at in range(0, len(runs), 20):
        text.append("    " + ",".join(f"0x{value:02x}" for value in runs[at:at+20]) + ",")
    text.append("};\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(text))
    return {"bytes": len(runs), "pixels": len(values),
            "gray4_sha256": hashlib.sha256(values).hexdigest(),
            "runs_sha256": hashlib.sha256(runs).hexdigest()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    print(json.dumps(pack(args.source, args.output), indent=2))
